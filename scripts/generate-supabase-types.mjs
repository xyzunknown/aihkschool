import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const outputPath = resolve(projectRoot, "src/types/database.generated.ts");
const envPath = resolve(projectRoot, ".env.local");
const checkMode = process.argv.includes("--check");

function readEnvFile(filePath) {
  try {
    const content = readFileSync(filePath, "utf8");
    return Object.fromEntries(
      content
        .split(/\r?\n/)
        .map((line) => line.trim())
        .filter((line) => line && !line.startsWith("#") && line.includes("="))
        .map((line) => {
          const index = line.indexOf("=");
          const key = line.slice(0, index).trim();
          const rawValue = line.slice(index + 1).trim();
          const value = rawValue.replace(/^['\"]|['\"]$/g, "");
          return [key, value];
        }),
    );
  } catch {
    return {};
  }
}

function resolveProjectRef() {
  if (process.env.SUPABASE_PROJECT_REF) return process.env.SUPABASE_PROJECT_REF;

  const envLocal = readEnvFile(envPath);
  const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL ?? envLocal.NEXT_PUBLIC_SUPABASE_URL;
  if (!supabaseUrl) {
    throw new Error(
      "Missing NEXT_PUBLIC_SUPABASE_URL. Set it in .env.local or export SUPABASE_PROJECT_REF.",
    );
  }

  return new URL(supabaseUrl).hostname.split(".")[0];
}

function generateTypes(projectRef) {
  const result = spawnSync(
    process.platform === "win32" ? "npx.cmd" : "npx",
    ["supabase", "gen", "types", "typescript", "--project-id", projectRef, "--schema", "public"],
    {
      cwd: projectRoot,
      encoding: "utf8",
      env: process.env,
      maxBuffer: 1024 * 1024 * 16,
    },
  );

  if (result.status !== 0) {
    const message = (result.stderr || result.stdout || "").trim();
    throw new Error(
      [
        "Supabase type generation failed.",
        message || "Unknown CLI error.",
        "If this machine has not logged into Supabase CLI yet, run `npx supabase login` or export SUPABASE_ACCESS_TOKEN before retrying.",
      ].join("\n\n"),
    );
  }

  const body = result.stdout.trim();
  if (!body.startsWith("export type Json")) {
    throw new Error("Unexpected Supabase CLI output. Refusing to overwrite generated types.");
  }

  return [
    "// ============================================================",
    "// HKSchoolPlace — Generated by `npm run supabase:types`",
    "// DO NOT EDIT MANUALLY.",
    "// ============================================================",
    "",
    body,
    "",
  ].join("\n");
}

try {
  const projectRef = resolveProjectRef();
  const nextContent = generateTypes(projectRef);

  if (checkMode) {
    const currentContent = readFileSync(outputPath, "utf8");
    if (currentContent !== nextContent) {
      console.error("Generated Supabase types are out of date. Run `npm run supabase:types`.");
      process.exit(1);
    }
    console.log("Generated Supabase types are up to date.");
    process.exit(0);
  }

  writeFileSync(outputPath, nextContent, "utf8");
  console.log(`Updated ${outputPath}`);
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}
